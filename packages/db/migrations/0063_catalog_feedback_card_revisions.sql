-- Card definitions become versioned. catalog_feedback_round_cards stays append-only and
-- keeps revision 1; later revisions live here. A product that already has a feedback entry
-- keeps the card snapshot stored with that entry, so a revision never changes recorded work.
CREATE TABLE catalog_feedback_round_card_revisions (
  round_no integer NOT NULL,
  position integer NOT NULL,
  revision integer NOT NULL CHECK (revision > 1),
  definition jsonb NOT NULL CHECK (jsonb_typeof(definition) = 'object'),
  note text NOT NULL CHECK (length(trim(note)) BETWEEN 1 AND 600),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (round_no, position, revision),
  FOREIGN KEY (round_no, position) REFERENCES catalog_feedback_round_cards(round_no, position)
);
