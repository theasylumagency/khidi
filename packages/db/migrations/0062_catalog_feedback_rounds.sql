CREATE TABLE catalog_feedback_round_cards (
  round_no integer NOT NULL CHECK (round_no > 0),
  position integer NOT NULL CHECK (position BETWEEN 1 AND 20),
  wordpress_id integer NOT NULL UNIQUE,
  definition jsonb NOT NULL CHECK (jsonb_typeof(definition) = 'object'),
  schema_version integer NOT NULL DEFAULT 2 CHECK (schema_version >= 2),
  PRIMARY KEY (round_no, position)
);
CREATE TABLE catalog_feedback_round_surveys (
  round_no integer PRIMARY KEY,
  batch_id uuid NOT NULL REFERENCES catalog_review_batches(id),
  actor_id uuid NOT NULL REFERENCES users(id),
  answers jsonb NOT NULL CHECK (jsonb_typeof(answers) = 'array' AND jsonb_array_length(answers) = 3),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE catalog_feedback_round_decisions (
  round_no integer PRIMARY KEY REFERENCES catalog_feedback_round_surveys(round_no),
  actor_id uuid NOT NULL REFERENCES users(id),
  choice text NOT NULL CHECK (choice IN ('KEEP','CHANGE')),
  note text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
